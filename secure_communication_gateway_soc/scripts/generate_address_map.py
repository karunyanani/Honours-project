    masters = cfg["masters"]
    slaves  = cfg["slaves"]

    lines = [C_HEADER]
    lines.append(f"/* Bus parameters */")
    lines.append(f"#define AXI_DATA_WIDTH  {bus['data_width']}u")
    lines.append(f"#define AXI_ADDR_WIDTH  {bus['addr_width']}u")
    lines.append(f"#define AXI_ID_WIDTH    {bus['id_width']}u")
    lines.append("")
    lines.append("/* Base addresses */")
    for s in slaves:
        lines.append(f"#define {s['name']}_BASE  0x{int(s['base'],16):08X}u")
    lines.append("")
    lines.append("/* Size of each slave window in bytes */")
    for s in slaves:
        lines.append(f"#define {s['name']}_SIZE  {s['size']}u")
    lines.append(C_REGDEFS)

    with open(outfile, "w") as f:
        f.write("\n".join(lines))
    print(f"  Written: {outfile}")


