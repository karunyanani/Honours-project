def gen_verilog(cfg, outfile):
    bus     = cfg["bus"]
    masters = cfg["masters"]
    slaves  = cfg["slaves"]
    n_s     = len(slaves)
    n_m     = len(masters)

    lines = [VERILOG_HEADER]

    # Bus parameters
    lines.append("// Bus parameters")
    lines.append(f"`define AXI_DATA_WIDTH  {bus['data_width']}")
    lines.append(f"`define AXI_ADDR_WIDTH  {bus['addr_width']}")
    lines.append(f"`define AXI_STRB_WIDTH  {bus['strb_width']}")
    lines.append(f"`define AXI_ID_WIDTH    {bus['id_width']}")
    lines.append("")

    # M-port index constants
    lines.append("// M-port index constants (matches M_COUNT instantiation order)")
    for s in slaves:
        lines.append(f"`define M_{s['name']:<8}{s['index']:3}   // {s['desc']}")
    lines.append("")

    # Base addresses
    lines.append("// Base addresses")
    for s in slaves:
        hex_val = int(s["base"], 16)
        hi = (hex_val >> 16) & 0xFFFF
        lo = hex_val & 0xFFFF
        lines.append(f"`define {s['name']}_BASE  32'h{hi:04X}_{lo:04X}")
    lines.append("")

    # Address window widths
    lines.append("// Address-window size (log2 bytes) for each slave")
    for s in slaves:
        lines.append(f"`define {s['name']}_ADDR_W  32'd{s['addr_width']}")
    lines.append("")

    # Connectivity masks  (bit per master, bit0 = master 0 = CPU)
    lines.append("// Access-control connectivity masks")
    lines.append("// Bit 0 = master 0 (CPU), bit 1 = master 1 (DMA)")
    for s in slaves:
        mask = 0
        for m in masters:
            if s["access"].get(m["name"], False):
                mask |= (1 << m["index"])
        bit_str = f"{n_m}'b" + format(mask, f'0{n_m}b')
        lines.append(f"`define CONN_{s['name']:<6}  {bit_str}")
    lines.append("")

    # Packed interconnect parameters (for axi_interconnect instantiation)
    # M_BASE_ADDR: concatenated base addresses (slave 0 at MSBs)
    base_concat  = ""
    aw_concat    = ""
    conn_concat  = ""
    for s in reversed(slaves):
        hex_val = int(s["base"], 16)
        hi = (hex_val >> 16) & 0xFFFF
        lo = hex_val & 0xFFFF
        base_concat += f"{hex_val:08x}"
        aw_concat   += f"{s['addr_width']:08x}"
    for s in reversed(slaves):
        mask = 0
        for m in masters:
            if s["access"].get(m["name"], False):
                mask |= (1 << m["index"])
        conn_concat += format(mask, f'0{n_m}b')

    total_base_bits = n_s * bus["addr_width"]
    total_aw_bits   = n_s * 32
    total_conn_bits = n_s * n_m

    lines.append("// Packed interconnect parameters (used in axi_interconnect instantiation)")
    lines.append(f"// M_BASE_ADDR  = {total_base_bits}'h{int(base_concat,16):0{total_base_bits//4}X}")
    lines.append(f"// M_ADDR_WIDTH = {total_aw_bits}'h{int(aw_concat,16):0{total_aw_bits//4}X}")
    lines.append(f"// M_CONNECT    = {total_conn_bits}'b{conn_concat}")
    lines.append("")

    # Address map summary comment
    lines.append("// Address map summary:")
    for s in slaves:
        base = int(s["base"], 16)
        top  = base + s["size"] - 1
        mask = 0
        for m in masters:
            if s["access"].get(m["name"], False):
                mask |= (1 << m["index"])
        lines.append(f"//   M{s['index']} {s['name']:<6}  {s['base']} - 0x{top:08X}"
                     f"  ({s['size']} B)  mask={format(mask, f'0{n_m}b')}")
    lines.append("")

    # Register offsets + AXI codes
    lines.append(VERILOG_REGDEFS)

    with open(outfile, "w") as f:
        f.write("\n".join(lines))
    print(f"  Written: {outfile}")


