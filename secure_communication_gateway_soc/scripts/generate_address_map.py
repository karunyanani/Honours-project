#!/usr/bin/env python3
# =============================================================================
# generate_address_map.py
#
# Reads config/address_map.yaml and generates three output files:
#
#   1. rtl/bus/soc_defines.vh        – Verilog `define macros (address map,
#                                      bus parameters, register offsets,
#                                      connectivity masks, AXI response codes)
#   2. sw/include/soc_map.h          – C firmware header (#define constants)
#   3. tb/soc_tb_defines.svh         – SystemVerilog testbench constants
#
# Usage:
#   python3 scripts/generate_address_map.py [--yaml config/address_map.yaml]
#                                           [--outdir .]
#
# Spec refs:
#   Section 4  – address map requirements
#   Section 5  – master access-control requirements
# =============================================================================

import argparse
import math
import sys
import os

try:
    import yaml
except ImportError:
    print("ERROR: PyYAML is required.  Install with: pip3 install pyyaml", file=sys.stderr)
    sys.exit(1)


# ---------------------------------------------------------------------------
# Helper
# ---------------------------------------------------------------------------
def log2_ceil(n):
    """Return ceil(log2(n)), minimum 1."""
    if n <= 1:
        return 1
    return math.ceil(math.log2(n))


def validate(cfg):
    """Sanity-check the loaded YAML configuration."""
    masters = {m["name"]: m["index"] for m in cfg["masters"]}
    slaves  = cfg["slaves"]

    # Check addr_width matches size
    for s in slaves:
        expected_aw = log2_ceil(s["size"])
        if s["addr_width"] != expected_aw:
            print(f"WARNING: slave {s['name']}: addr_width={s['addr_width']} "
                  f"but ceil(log2({s['size']}))={expected_aw}.  Using computed value.",
                  file=sys.stderr)
            s["addr_width"] = expected_aw

    # Check no overlap
    regions = []
    for s in slaves:
        base = int(s["base"], 16)
        top  = base + s["size"] - 1
        for (n, b, t) in regions:
            if base <= t and top >= b:
                print(f"ERROR: slaves {n} and {s['name']} address regions overlap!",
                      file=sys.stderr)
                sys.exit(1)
        regions.append((s["name"], base, top))

    # Check all masters listed in every slave's access block
    for s in slaves:
        for m in masters:
            if m not in s.get("access", {}):
                print(f"ERROR: master '{m}' not listed in slave '{s['name']}' access block",
                      file=sys.stderr)
                sys.exit(1)


