def gen_sv_defines(cfg, outfile):
    slaves  = cfg["slaves"]
    masters = cfg["masters"]
    n_m     = len(masters)

    lines = [SV_HEADER]
    lines.append("// Bus parameters")
    lines.append(f"parameter int AXI_DW  = {cfg['bus']['data_width']};")
    lines.append(f"parameter int AXI_AW  = {cfg['bus']['addr_width']};")
    lines.append(f"parameter int AXI_IDW = {cfg['bus']['id_width']};")
    lines.append("")
    lines.append("// Slave base addresses")
    for s in slaves:
        lines.append(f"parameter logic [31:0] {s['name']}_BASE = 32'h{int(s['base'],16):08X};")
    lines.append("")
    lines.append("// Slave sizes")
    for s in slaves:
        lines.append(f"parameter int {s['name']}_SIZE = {s['size']};")
    lines.append("")
    lines.append("// Access control: 1=allowed, 0=denied (index = master index)")
    for s in slaves:
        mask = 0
        for m in masters:
            if s["access"].get(m["name"], False):
                mask |= (1 << m["index"])
        lines.append(f"parameter logic [{n_m-1}:0] CONN_{s['name']} = {n_m}'b{format(mask, f'0{n_m}b')};")
    lines.append(SV_REGDEFS)

    with open(outfile, "w") as f:
        f.write("\n".join(lines))
    print(f"  Written: {outfile}")


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------
def main():
    parser = argparse.ArgumentParser(
        description="Generate Verilog, C, and SystemVerilog address-map files from YAML")
    parser.add_argument("--yaml",   default="config/address_map.yaml",
                        help="Path to address_map.yaml (default: config/address_map.yaml)")
    parser.add_argument("--outdir", default=".",
                        help="Project root directory (default: current directory)")
    args = parser.parse_args()

    yaml_path = os.path.join(args.outdir, args.yaml) if not os.path.isabs(args.yaml) else args.yaml
    if not os.path.exists(yaml_path):
        print(f"ERROR: YAML file not found: {yaml_path}", file=sys.stderr)
        sys.exit(1)

    with open(yaml_path) as f:
        cfg = yaml.safe_load(f)

    validate(cfg)

    root = args.outdir
    os.makedirs(os.path.join(root, "rtl", "interconnect"), exist_ok=True)
    os.makedirs(os.path.join(root, "rtl", "bus"),          exist_ok=True)
    os.makedirs(os.path.join(root, "sw",  "include"),      exist_ok=True)
    os.makedirs(os.path.join(root, "tb"),                  exist_ok=True)

    gen_verilog(cfg,    os.path.join(root, "rtl", "interconnect", "soc_defines.vh"))
    gen_verilog(cfg,    os.path.join(root, "rtl", "bus", "soc_defines.vh"))
    gen_c_header(cfg,   os.path.join(root, "sw",  "include", "soc_map.h"))
    gen_sv_defines(cfg, os.path.join(root, "tb",  "soc_tb_defines.svh"))

    print("Address-map generation complete.")


if __name__ == "__main__":
    main()
